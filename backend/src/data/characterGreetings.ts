/**
 * 親密度レベルからティアを判定し、対応する挨拶をランダムに1つ返す
 * （Lv.10で常連ティア、それ以外は通常ティア。対象データが無いキャラはnull）
 */
export function pickCharacterGreeting(characterId: CharacterId, intimacyLevel: number): { text: string; tier: 'regular' | 'veteran' } | null {
  const set = CHARACTER_GREETINGS[characterId]
  if (!set) return null
  const tier: 'regular' | 'veteran' = intimacyLevel >= 10 ? 'veteran' : 'regular'
  const pool = set[tier]
  const text = pool[Math.floor(Math.random() * pool.length)]
  return { text, tier }
}
