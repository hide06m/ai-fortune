/** 82以上の画数は、80を引いた数として扱う */
export function normalizeStrokeNumber(n: number): number {
  if (n <= 0) return 1
  return n > 81 ? ((n - 1) % 80) + 1 : n
}

export function seimeiNumberOf(n: number): SeimeiNumber {
  return SEIMEI_NUMBERS[normalizeStrokeNumber(n)]
}
