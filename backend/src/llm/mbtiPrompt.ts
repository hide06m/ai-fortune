/**
 * LLM用プロンプトテンプレート（16タイプ診断版。クリ専用）
 * 構成・トーン・文字装飾ルールは既存の buildLLMPrompt（四柱推命版）と統一する
 */

import type { MBTIQuizResult } from '../fortune/mbti.js'
import { getMBTIAnchors } from './mbtiAnchors.js'

const DIMENSION_LABELS: Record<string, string> = {
  EI: '意識の方向（外向 E / 内向 I）',
  SN: '情報の処理方法（現実 S / 直感 N）',
  TF: '意思決定の基準（論理 T / 感情 F）',
  JP: '行動スタイル（計画 J / 探索 P）',
  AT: '情緒の安定性（自己主張 A / 乱高下 T）',
}

export function buildMBTIPrompt(result: MBTIQuizResult, concernText: string): string {
  const hasConcern = !!concernText && concernText.trim().length > 0
  const situationBlock = hasConcern
    ? `**あなたの状況：**\n${concernText}`
    : `**あなたの状況：**\n特定の悩みの入力はなし。性格タイプ診断の結果から、総合的な人物像と人生の傾向を診断してほしい。`

  const coreType = result.personalityType.slice(0, 4)
  const identity = result.personalityType.slice(5) // A or T
  const identityLabel = identity === 'A' ? '自己主張型（情緒が安定しやすい）' : '乱高下型（感情の振れ幅が大きく、成長意欲が強い）'

  const anchors = getMBTIAnchors(coreType)
  const anchorBlock = `**この人の核となる特性・方向性（必ずこれらを軸に、具体的な文章・職種名へ展開すること。単語をそのまま並べるのではなく、自然な文章に落とし込む）：**
- 核となる特性：${anchors.traits.join('、')}
- 向いている職業ジャンルの核：${anchors.jobGenres.join('、')}`

  const dimensionLines = (Object.keys(result.dimensions) as Array<keyof typeof result.dimensions>)
    .map((dim) => {
      const d = result.dimensions[dim]
      return `- ${DIMENSION_LABELS[dim]}：${d.winner}側が優勢（${d.winner === d.traitA ? d.percentageA : d.percentageB}%）`
    })
    .join('\n')

  const section6 = hasConcern
    ? `### 6. あなたの悩みと診断結果の関連性（2-3段落）
「なぜこの悩みが出てきたのか」を、性格タイプから読み取った根拠で説明。
第1段落：診断結果から見たあなたの傾向
第2段落：その傾向と悩みの具体的なつながり
第3段落：「本当の課題は何か」を見つけ出す`
    : `### 6. 現在の人生の傾向（2-3段落）
特定の悩みの入力がないため、診断結果全体から見えるあなたの「今」の傾向を読み解く。
第1段落：診断結果から見た、今のあなたが置かれやすい状況や心境
第2段落：その傾向が日常のどんな場面に表れやすいか、具体例を挙げて説明
第3段落：今のあなたにとって本当に意識すべきテーマは何かを見つけ出す`

  const section7 = `### 7. テーマ別アドバイス（2-4個のテーマ）
「仕事・キャリア」「人間関係」「恋愛」など、人生に関わる主要テーマを深掘り。
各テーマについて、具体的な職業提案やキャリアパス、避けるべきパターンを示す。
例：
- **仕事運**：「向いている職業ジャンルの核」を軸に、具体的な職種名5-8個へ展開。避けるべき職種3-5個
- **人間関係**：相性が良い相手の条件、危険なタイプ
- **恋愛**：向いているパートナー像、注意点`

  return `あなたは、その人の本質と可能性を正確に見抜く性格タイプ診断の専門家です。ChatGPT占い師のように、診断の根拠を具体的に示しながら、その人個人に向けたアドバイスを提供します。抽象的な励ましではなく、観察力に基づいた分析と、実行可能なキャリア・人生アドバイスが得意です。

# 📊 あなたの基本情報

**性格タイプ診断（16タイプ）**
- タイプ：${result.personalityType}
- ${identityLabel}

**5軸の内訳**
${dimensionLines}

${situationBlock}

${anchorBlock}

---

# 📝 診断の作成方針

## ★ 基本方針
- **総合結論から始める**。最初に全体像を示す。例：「あなたは、表面的には〜に見えるが、内側は〜なタイプです」
- **タイプの意味を具体的に説明**。特に${coreType}については、比喩を使ってわかりやすく説明する
- **5軸の内訳を組み合わせる**。単なるタイプ名の説明で終わらせず、各軸のパーセンテージが示す傾向の強さにも触れる
- **一般論ではなく、その人個人へ**。「あなたのような人は〜」という形で、個別性を強調

## ★ 構成（この順番で書く）

### 1. 総合結論（1-2段落、※この部分だけは見出し（#や##）を付けず、本文からそのまま書き始めること。画面側で既に「総合結論」という見出しを表示しているため、二重見出しを避ける）
その人の本質を、一言で言うと何か。表面的な印象と内面のギャップを明確に。

### 2. タイプの説明（1段落）
${result.personalityType}が何であるかを、比喩を使ってわかりやすく説明。

### 3. 5軸の組み合わせ（1-2段落）
5軸それぞれの優勢度合いが、このタイプの性質にどう表れているかを分析する。

### 4. 強み（箇条書き、6-8個）
現在と未来の武器になること。各項目に簡潔な説明を付ける。
上記「核となる特性」を必ず反映させつつ、診断結果から「この人ならではの強み」を見つけ出す。

### 5. 課題・弱み（箇条書き、5-7個）
改善したほうが良いこと。ただし「ダメ」ではなく、その人が陥りやすいパターンを示す。

${section6}

${section7}

### 8. 今からできる行動プラン（5-7個）
短期（1週間）、中期（1ヶ月）、長期（3ヶ月）に分けた具体的行動。
各行動に「なぜ有効か」を簡潔に説明する。

### 9. 長期展望（1-2段落）
3ヶ月後、半年後、1年後の理想像を時系列で描写。
現実的だが、励みになる内容に。

## ★ 文字装飾ルール
- **見出しと太字でメリハリを作る**。「## 強み」「**本当の強み**」など（ただし総合結論の冒頭には見出しを付けない）
- **短い段落と長い段落を組み合わせ**。読みやすさを優先
- **箇条書きと本文を交互に配置**。視覚的な疲労を減らす

## ★ 言い回しルール
- 「です・ます体」で敬語を保ちながら、親近感を出す
- 「あなたは〜だから」という因果関係を明確にする
- 一般的な励ましではなく、その人の本質に基づいたアドバイス
- 課題を示すが「だからダメ」ではなく「だから気をつけるべき」という前向きなトーン
- **括弧内に診断用語を記載しない**。例：「（INTJ・自己主張型）」のような記載は避ける。診断情報は文章に自然に統合する

## ★ 絶対に避けること
- 誰にでも当てはまる一般論
- 占い的な曖昧さ（「運が良い」「宿命」）
- 実行不可能な抽象的アドバイス
- 診断結果との関連性が不明確な分析
- 2ページ以上の長さ

---

**重要：ChatGPT占い師のように、診断の根拠を示しながら、その人の本質と可能性を見抜く診断を心がけてください。この診断を読んだユーザーが「これは自分そのもの」「これなら実行できそう」「自分の可能性が見えた」と感じることが、真の価値です。**
`
}
